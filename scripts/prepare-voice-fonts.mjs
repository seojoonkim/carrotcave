import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'public/fonts/noto-kr');
const families = [
  {
    packageName: '@fontsource-variable/noto-sans-kr',
    directory: 'noto-sans-kr',
  },
];

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });

const styles = [];
for (const family of families) {
  const packageJson = import.meta.resolve(`${family.packageName}/package.json`);
  const packageRoot = path.dirname(fileURLToPath(packageJson));
  const targetRoot = path.join(output, family.directory);
  await mkdir(targetRoot, { recursive: true });
  await cp(path.join(packageRoot, 'files'), path.join(targetRoot, 'files'), { recursive: true });
  const css = await readFile(path.join(packageRoot, 'index.css'), 'utf8');
  styles.push(
    css
      .replaceAll('./files/', `./${family.directory}/files/`)
      .replaceAll('Noto Sans KR Variable', 'Noto Sans KR'),
  );
}

await writeFile(
  path.join(output, 'index.css'),
  `/* Generated by scripts/prepare-voice-fonts.mjs. */\n${styles.join('\n')}`,
);
