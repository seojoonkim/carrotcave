#!/usr/bin/env node
// Voice readers get the same "reading end" as posts (carrot mark → next → 3-way actions → 3 picks).
// Content stays out of each transcript HTML: this script writes ONE runtime file
// (public/voices/reading-end.js, data + renderer) and gives each reader only a mount point
// + the shared stylesheet/script tags. Idempotent.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { interviews } from '../data/interviews.ts';
const EN_VOICES = JSON.parse(readFileSync(new URL('../data/en/voices.json', import.meta.url), 'utf8'));

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- READING-END:START -->';
const END = '<!-- READING-END:END -->';

const voices = interviews
  .filter((v) => v.status === 'published' && existsSync(path.join(root, 'public', v.embedPath)))
  .map(({ slug, name, title, summary, duration, thumbnailUrl, sourceUrl }) => ({ slug, name, title, summary, duration, thumbnailUrl: thumbnailUrl ?? null, sourceUrl, video: /youtube\.com|youtu\.be|vimeo\.com/.test(sourceUrl), en: EN_VOICES[slug] ? { name: EN_VOICES[slug].name, title: EN_VOICES[slug].title, summary: EN_VOICES[slug].summary } : null }));

const runtime = `/* generated by scripts/build-voice-reading-end.mjs — do not edit */
(function () {
  var VOICES = ${JSON.stringify(voices)};
  var mount = document.getElementById('cc-reading-end');
  if (!mount) return;
  var slug = mount.getAttribute('data-voice');
  var EN = document.documentElement.lang === 'en' || new URLSearchParams(location.search).get('lang') === 'en';
  if (EN) VOICES = VOICES.map(function (v) { return v.en ? Object.assign({}, v, v.en) : v; });
  var T = EN ? { rank: function (n) { return '#' + n; }, voice: 'Voices', read: 'Read this voice', end: 'After reading', next: 'Next in Voices', nav: 'Voice navigation', back: 'Back to Voices', backShort: 'Back', share: 'Share', video: 'Watch original video', videoShort: 'Video', source: 'View original', sourceShort: 'Original', heading: 'Three voices to hear next', intro: 'Picked to follow the conversation and ideas you just read.', recs: 'Recommended voices', copied: 'Link copied', failed: 'Copy failed', base: '/en/voices/' }
    : { rank: function (n) { return n + '순위'; }, voice: '목소리', read: '이 목소리 읽기', end: '다 읽은 뒤', next: '목소리의 다음 편', nav: '목소리 이동', back: '목소리로 돌아가기', backShort: '돌아가기', share: '공유하기', video: '원본 영상 보기', videoShort: '원본 영상', source: '원본 보기', sourceShort: '원본', heading: '다음으로 들어볼 목소리 3개', intro: '지금 읽은 대화와 생각이 이어지는 순서대로 골랐습니다.', recs: '이어 읽을 목소리 추천', copied: '링크 복사됨', failed: '복사 실패', base: '/voices/' };
  var i = VOICES.findIndex(function (v) { return v.slug === slug; });
  if (i < 0) return;
  function esc(s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;'); }
  function at(k) { return VOICES[(i + k) % VOICES.length]; }
  var me = VOICES[i], next = at(1);
  var picks = [2, 3, 4].map(at).filter(function (v) { return v.slug !== slug; });
  var BACK = '<svg viewBox="0 0 20 20" aria-hidden="true"><path d="M16 10H4m0 0 5-5m-5 5 5 5" /></svg>';
  var SHARE = '<svg class="post-share-icon" viewBox="0 0 20 20" aria-hidden="true"><path d="M10 13V3m0 0L6.5 6.5M10 3l3.5 3.5M4 10.5v4A1.5 1.5 0 0 0 5.5 16h9a1.5 1.5 0 0 0 1.5-1.5v-4" /></svg>';
  var PLAY = '<svg viewBox="0 0 20 20" aria-hidden="true"><rect x="2.5" y="4.5" width="15" height="11" rx="3" /><path d="m8.5 7.8 3.6 2.2-3.6 2.2Z" /></svg>';
  function pick(v, n) {
    return '<li class="cave-constellation__recommendation"><article>' +
      '<header class="cave-constellation__recommendation-header"><span class="cave-constellation__rank"><span>' + T.rank(n) + '</span></span><strong class="cave-constellation__relationship-type">' + esc(EN ? String(v.duration).replace(/^(\\d+)개 구간$/, '$1 segments').replace(/^(\\d+)개 장$/, '$1 chapters') : v.duration) + '</strong></header>' +
      '<a class="cave-constellation__thumbnail" data-has-image="' + (v.thumbnailUrl ? 'true' : 'false') + '" href="' + T.base + v.slug + '" target="_top" tabindex="-1" aria-hidden="true">' +
        (v.thumbnailUrl ? '<img src="' + esc(v.thumbnailUrl) + '" alt="" loading="lazy" decoding="async">' : '') +
        '<div class="cave-constellation__thumbnail-copy"><span class="cave-constellation__thumbnail-category">' + T.voice + ' · ' + esc(v.name) + '</span><h3>' + esc(v.title) + '</h3><p>' + esc(v.summary) + '</p></div>' +
      '</a>' +
      '<a class="cave-constellation__navigate" href="' + T.base + v.slug + '" target="_top">' + T.read + ' <span class="cave-constellation__carrot" aria-hidden="true"></span></a>' +
    '</article></li>';
  }
  var end = document.createElement('section');
  end.className = 'cc-reading-end';
  end.setAttribute('aria-label', T.end);
  end.innerHTML =
    '<div class="cc-reading-end__mark" aria-hidden="true"></div>' +
    '<a class="post-next" href="' + T.base + next.slug + '" target="_top"><span class="post-next__label">' + T.next + '</span><span class="post-next__title">' + esc(next.name) + ' · ' + esc(next.title) + '</span><span class="post-next__arrow" aria-hidden="true">→</span></a>' +
    '<nav class="post-reader-actions post-reader-actions--after-content" aria-label="' + T.nav + '">' +
      '<a class="post-reader-action" href="' + T.base.slice(0, -1) + '" target="_top">' + BACK + '<span class="post-reader-action__long">' + T.back + '</span><span class="post-reader-action__short">' + T.backShort + '</span></a>' +
      '<button type="button" class="post-reader-action post-reader-action--share" aria-live="polite">' + SHARE + '<span class="post-reader-action__label">' + T.share + '</span></button>' +
      '<a class="post-reader-action post-reader-action--source" href="' + esc(me.sourceUrl) + '" target="_blank" rel="noopener noreferrer">' + PLAY + '<span class="post-reader-action__long">' + (me.video ? T.video : T.source) + '</span><span class="post-reader-action__short">' + (me.video ? T.videoShort : T.sourceShort) + '</span></a>' +
    '</nav>' +
    '<div class="cave-constellation-shell cave-constellation-shell--after-actions">' +
      '<p class="cave-constellation-kicker">DOWN THE RABBIT HOLE</p>' +
      '<h2 class="cave-constellation-heading">' + T.heading + '</h2>' +
      '<p class="cave-constellation-intro">' + T.intro + '</p>' +
      '<section class="cave-constellation" aria-label="' + T.recs + '"><ol class="cave-constellation__recommendations">' +
        picks.map(function (v, n) { return pick(v, n + 1); }).join('') +
      '</ol></section>' +
    '</div>';
  mount.replaceWith(end);

  var btn = end.querySelector('.post-reader-action--share');
  var label = btn.querySelector('.post-reader-action__label');
  var timer;
  function show(s) { label.textContent = s; clearTimeout(timer); timer = setTimeout(function () { label.textContent = T.share; }, 1800); }
  function copy(u) {
    if (navigator.clipboard && navigator.clipboard.writeText) return navigator.clipboard.writeText(u);
    return new Promise(function (ok, fail) { var a = document.createElement('textarea'); a.value = u; a.style.position = 'fixed'; a.style.opacity = '0'; document.body.appendChild(a); a.select(); var done = document.execCommand('copy'); a.remove(); done ? ok() : fail(); });
  }
  btn.addEventListener('click', function () {
    var url = 'https://carrotcave.com' + T.base + slug;
    var shared = navigator.share ? navigator.share({ title: me.name + ' · ' + me.title, url: url }) : Promise.reject({ name: 'NoShare' });
    shared.catch(function (e) { if (e && e.name === 'AbortError') return; return copy(url).then(function () { show(T.copied); }, function () { show(T.failed); }); });
  });
})();
`;
writeFileSync(path.join(root, 'public/voices/reading-end.js'), runtime);

let changed = 0;
for (const voice of voices) {
  const file = path.join(root, 'public/voices', voice.slug, 'index.html');
  let html = readFileSync(file, 'utf8');
  const before = html;
  for (const href of ['/fonts/pretendard/pretendardvariable-dynamic-subset.css', '/reading-end.css']) {
    if (!html.includes(`href="${href}"`)) html = html.replace('<link rel="stylesheet" href="../reader-system.css">', `<link rel="stylesheet" href="../reader-system.css"><link rel="stylesheet" href="${href}">`);
  }
  const block = `${START}<div id="cc-reading-end" data-voice="${voice.slug}"></div><script src="/voices/reading-end.js" defer></script>${END}`;
  if (html.includes(START)) html = html.replace(new RegExp(`${START}[\\s\\S]*?${END}`), block);
  else {
    const m = html.match(/<\/div>\s*<\/div>\s*<\/main>/);
    if (!m) throw new Error(`${voice.slug}: no content-column end anchor`);
    html = html.slice(0, m.index) + block + html.slice(m.index);
  }
  if (html !== before) { writeFileSync(file, html); changed += 1; }
}
console.log(`voice reading-end: ${voices.length} voices, ${changed} readers updated, runtime written`);
