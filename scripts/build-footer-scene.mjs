// Builds components/footer-scene-svg.ts from public/brand/footer-cave.svg (written by scripts/brand/build_brand.py).
// The footer inlines the illustration so menu moods, time of day, the NEW flag and the carrot tap can reach inside it.
// Every rule of the svg's own <style> is scoped under .footer-scene so nothing leaks into the site.
import { readFileSync, writeFileSync } from 'node:fs';

export const SCOPE = '.footer-scene';

function scopeSelectors(sel) {
  return sel.split(',').map((s) => s.trim()).filter(Boolean).map((s) => `${SCOPE} ${s}`).join(',');
}

export function scopeCss(css) {
  let out = '';
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) { out += css.slice(i); break; }
    const head = css.slice(i, open).trim();
    // find matching close brace
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (/^@keyframes/.test(head)) out += `${head}{${body}}`;
    else if (/^@media/.test(head)) out += `${head}{${scopeCss(body)}}`;
    else out += `${scopeSelectors(head)}{${body}}`;
    i = j;
  }
  return out;
}

export function buildFooterSceneSvg(svg) {
  let s = svg.replace(/<\?xml[^>]*>\s*/, '');
  s = s.replace(/<style>([\s\S]*?)<\/style>/g, (_, css) => `<style>${scopeCss(css).replace(/\s*\n\s*/g, '')}</style>`);
  s = s.replace('<svg ', '<svg class="footer-rabbit-carrot" preserveAspectRatio="xMaxYMax slice" focusable="false" ');
  s = s.replace(/ role="img" aria-labelledby="[^"]*"/, ' aria-hidden="true"');
  s = s.replace(/<title[^>]*>[\s\S]*?<\/title>\s*/, '').replace(/<desc[^>]*>[\s\S]*?<\/desc>\s*/, '');
  return s.replace(/>\s+</g, '><').trim();
}

export function buildFooterSceneModule(svg) {
  return `// Generated by scripts/build-footer-scene.mjs from public/brand/footer-cave.svg. Do not edit by hand.\nexport const FOOTER_SCENE_SVG = ${JSON.stringify(buildFooterSceneSvg(svg))};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = new URL('../', import.meta.url);
  const svg = readFileSync(new URL('public/brand/footer-cave.svg', root), 'utf8');
  writeFileSync(new URL('components/footer-scene-svg.ts', root), buildFooterSceneModule(svg));
  console.log('footer-scene-svg.ts written');
}
