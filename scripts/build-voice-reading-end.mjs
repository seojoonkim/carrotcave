#!/usr/bin/env node
// Voice readers get the same "reading end" as posts (carrot mark → next → 3-way actions → 3 picks).
// Content stays out of each transcript HTML: this script writes ONE runtime file
// (public/voices/reading-end.js, data + renderer) and gives each reader only a mount point
// + the shared stylesheet/script tags. Idempotent.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { interviews } from '../data/interviews.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- READING-END:START -->';
const END = '<!-- READING-END:END -->';

const voices = interviews
  .filter((v) => v.status === 'published' && existsSync(path.join(root, 'public', v.embedPath)))
  .map(({ slug, name, title, summary, duration, thumbnailUrl, sourceUrl }) => ({ slug, name, title, summary, duration, thumbnailUrl: thumbnailUrl ?? null, sourceUrl, video: /youtube\.com|youtu\.be|vimeo\.com/.test(sourceUrl) }));

const runtime = `/* generated by scripts/build-voice-reading-end.mjs — do not edit */
(function () {
  var VOICES = ${JSON.stringify(voices)};
  var mount = document.getElementById('cc-reading-end');
  if (!mount) return;
  var slug = mount.getAttribute('data-voice');
  var i = VOICES.findIndex(function (v) { return v.slug === slug; });
  if (i < 0) return;
  function esc(s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;'); }
  function at(k) { return VOICES[(i + k) % VOICES.length]; }
  var me = VOICES[i], next = at(1);
  var picks = [2, 3, 4].map(at).filter(function (v) { return v.slug !== slug; });
  var BACK = '<svg viewBox="0 0 20 20" aria-hidden="true"><path d="M16 10H4m0 0 5-5m-5 5 5 5" /></svg>';
  var SHARE = '<svg class="post-share-icon" viewBox="0 0 20 20" aria-hidden="true"><path d="M10 13V3m0 0L6.5 6.5M10 3l3.5 3.5M4 10.5v4A1.5 1.5 0 0 0 5.5 16h9a1.5 1.5 0 0 0 1.5-1.5v-4" /></svg>';
  var PLAY = '<svg viewBox="0 0 20 20" aria-hidden="true"><rect x="2.5" y="4.5" width="15" height="11" rx="3" /><path d="m8.5 7.8 3.6 2.2-3.6 2.2Z" /></svg>';
  function pick(v, n) {
    return '<li class="cave-constellation__recommendation"><article>' +
      '<header class="cave-constellation__recommendation-header"><span class="cave-constellation__rank"><span>' + n + '순위</span></span><strong class="cave-constellation__relationship-type">' + esc(v.duration) + '</strong></header>' +
      '<a class="cave-constellation__thumbnail" data-has-image="' + (v.thumbnailUrl ? 'true' : 'false') + '" href="/voices/' + v.slug + '" target="_top" tabindex="-1" aria-hidden="true">' +
        (v.thumbnailUrl ? '<img src="' + esc(v.thumbnailUrl) + '" alt="" loading="lazy" decoding="async">' : '') +
        '<div class="cave-constellation__thumbnail-copy"><span class="cave-constellation__thumbnail-category">목소리 · ' + esc(v.name) + '</span><h3>' + esc(v.title) + '</h3><p>' + esc(v.summary) + '</p></div>' +
      '</a>' +
      '<a class="cave-constellation__navigate" href="/voices/' + v.slug + '" target="_top">이 목소리 읽기 <span class="cave-constellation__carrot" aria-hidden="true"></span></a>' +
    '</article></li>';
  }
  var end = document.createElement('section');
  end.className = 'cc-reading-end';
  end.setAttribute('aria-label', '다 읽은 뒤');
  end.innerHTML =
    '<div class="cc-reading-end__mark" aria-hidden="true"></div>' +
    '<a class="post-next" href="/voices/' + next.slug + '" target="_top"><span class="post-next__label">목소리의 다음 편</span><span class="post-next__title">' + esc(next.name) + ' · ' + esc(next.title) + '</span><span class="post-next__arrow" aria-hidden="true">→</span></a>' +
    '<nav class="post-reader-actions post-reader-actions--after-content" aria-label="목소리 이동">' +
      '<a class="post-reader-action" href="/voices" target="_top">' + BACK + '<span class="post-reader-action__long">목소리로 돌아가기</span><span class="post-reader-action__short">돌아가기</span></a>' +
      '<button type="button" class="post-reader-action post-reader-action--share" aria-live="polite">' + SHARE + '<span class="post-reader-action__label">공유하기</span></button>' +
      '<a class="post-reader-action post-reader-action--source" href="' + esc(me.sourceUrl) + '" target="_blank" rel="noopener noreferrer">' + PLAY + '<span class="post-reader-action__long">' + (me.video ? '원본 영상 보기' : '원본 보기') + '</span><span class="post-reader-action__short">' + (me.video ? '원본 영상' : '원본') + '</span></a>' +
    '</nav>' +
    '<div class="cave-constellation-shell cave-constellation-shell--after-actions">' +
      '<p class="cave-constellation-kicker">CAVE CONSTELLATION</p>' +
      '<h2 class="cave-constellation-heading">다음으로 들어볼 목소리 3개</h2>' +
      '<p class="cave-constellation-intro">지금 읽은 대화와 생각이 이어지는 순서대로 골랐습니다.</p>' +
      '<section class="cave-constellation" aria-label="이어 읽을 목소리 추천"><ol class="cave-constellation__recommendations">' +
        picks.map(function (v, n) { return pick(v, n + 1); }).join('') +
      '</ol></section>' +
    '</div>';
  mount.replaceWith(end);

  var btn = end.querySelector('.post-reader-action--share');
  var label = btn.querySelector('.post-reader-action__label');
  var timer;
  function show(s) { label.textContent = s; clearTimeout(timer); timer = setTimeout(function () { label.textContent = '공유하기'; }, 1800); }
  function copy(u) {
    if (navigator.clipboard && navigator.clipboard.writeText) return navigator.clipboard.writeText(u);
    return new Promise(function (ok, fail) { var a = document.createElement('textarea'); a.value = u; a.style.position = 'fixed'; a.style.opacity = '0'; document.body.appendChild(a); a.select(); var done = document.execCommand('copy'); a.remove(); done ? ok() : fail(); });
  }
  btn.addEventListener('click', function () {
    var url = 'https://carrotcave.com/voices/' + slug;
    var shared = navigator.share ? navigator.share({ title: me.name + ' · ' + me.title, url: url }) : Promise.reject({ name: 'NoShare' });
    shared.catch(function (e) { if (e && e.name === 'AbortError') return; return copy(url).then(function () { show('링크 복사됨'); }, function () { show('복사 실패'); }); });
  });
})();
`;
writeFileSync(path.join(root, 'public/voices/reading-end.js'), runtime);

let changed = 0;
for (const voice of voices) {
  const file = path.join(root, 'public/voices', voice.slug, 'index.html');
  let html = readFileSync(file, 'utf8');
  const before = html;
  for (const href of ['/fonts/pretendard/pretendardvariable-dynamic-subset.css', '/reading-end.css']) {
    if (!html.includes(`href="${href}"`)) html = html.replace('<link rel="stylesheet" href="../reader-system.css">', `<link rel="stylesheet" href="../reader-system.css"><link rel="stylesheet" href="${href}">`);
  }
  const block = `${START}<div id="cc-reading-end" data-voice="${voice.slug}"></div><script src="/voices/reading-end.js" defer></script>${END}`;
  if (html.includes(START)) html = html.replace(new RegExp(`${START}[\\s\\S]*?${END}`), block);
  else {
    const m = html.match(/<\/div>\s*<\/div>\s*<\/main>/);
    if (!m) throw new Error(`${voice.slug}: no content-column end anchor`);
    html = html.slice(0, m.index) + block + html.slice(m.index);
  }
  if (html !== before) { writeFileSync(file, html); changed += 1; }
}
console.log(`voice reading-end: ${voices.length} voices, ${changed} readers updated, runtime written`);
